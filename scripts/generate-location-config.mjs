import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(root, "location.config.json");
const config = JSON.parse(await readFile(sourcePath, "utf8"));

const required = ["id", "label", "latitude", "longitude"];
for (const key of required) {
  if (config[key] === undefined || config[key] === "") {
    throw new Error(`location.config.json requires ${key}`);
  }
}
if (!/^[a-z][a-z0-9_]{0,63}$/.test(config.id)) {
  throw new Error("location id must use lowercase letters, numbers, and underscores");
}
if (!Number.isFinite(config.latitude) || !Number.isFinite(config.longitude)) {
  throw new Error("latitude and longitude must be numbers copied from Google Maps");
}

const ts = `// Generated from location.config.json. Do not edit this file directly.\nexport const SENSOR_LOCATION = ${JSON.stringify(config, null, 2)} as const;\n`;
await writeFile(path.join(root, "web", "lib", "location.generated.ts"), ts);
